// Generate the topic coverage matrix from the actual content and write it into
// CURRICULUM_AUDIT.md and ROADMAP.md between <!-- coverage:start --> and
// <!-- coverage:end --> markers. Numbers are computed, never hand-written.
// Usage: npm run report:coverage
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadContent } from "../src/content/load.ts";

const root = resolve(import.meta.dirname, "..");
const content = loadContent(root);
const { index } = content;

const rows = index.stages.map((s) => {
  const ids = s.conceptIds;
  const cs = ids.map((id) => index.concepts[id]!);
  const lessons = cs.filter((c) => c.lessonId).length;
  const items = cs.reduce((n, c) => n + c.itemIds.length, 0);
  const projects = new Set(cs.flatMap((c) => c.projectIds)).size;
  const interview = new Set(cs.flatMap((c) => c.interviewIds)).size;
  const glossary = cs.reduce((n, c) => n + c.glossaryIds.length, 0);
  const withOutline = cs.filter((c) => c.keyIdeas.length >= 2 && c.misconceptions.length >= 1).length;
  const sources = cs.reduce((n, c) => n + c.sources.length, 0);
  const checked = cs.flatMap((c) => c.sources).filter((src) => index.links[src.url]?.ok).length;
  const essential = cs.filter((c) => c.priority === "essential").length;
  return { s, concepts: ids.length, essential, lessons, items, projects, interview, glossary, withOutline, sources, checked };
});

const total = rows.reduce(
  (t, r) => ({
    concepts: t.concepts + r.concepts,
    essential: t.essential + r.essential,
    lessons: t.lessons + r.lessons,
    items: t.items + r.items,
    projects: t.projects + r.projects,
    interview: t.interview + r.interview,
    glossary: t.glossary + r.glossary,
    withOutline: t.withOutline + r.withOutline,
    sources: t.sources + r.sources,
    checked: t.checked + r.checked,
  }),
  { concepts: 0, essential: 0, lessons: 0, items: 0, projects: 0, interview: 0, glossary: 0, withOutline: 0, sources: 0, checked: 0 },
);

const pct = (a: number, b: number) => (b ? `${Math.round((a / b) * 100)}%` : "—");
const table = [
  "| # | Stage | Concepts | Essential | Full lessons | Assessment items | Projects | Interview Qs | Glossary | Rich outlines¹ | Sources (link-checked²) |",
  "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
  ...rows.map(
    (r) =>
      `| ${r.s.order} | ${r.s.shortTitle} | ${r.concepts} | ${r.essential} | ${r.lessons} (${pct(r.lessons, r.concepts)}) | ${r.items} | ${r.projects} | ${r.interview} | ${r.glossary} | ${r.withOutline} | ${r.sources} (${r.checked}) |`,
  ),
  `| | **Total** | **${total.concepts}** | **${total.essential}** | **${total.lessons} (${pct(total.lessons, total.concepts)})** | **${total.items}** | **${index.stats.projects}** | **${index.stats.interviewQuestions}** | **${index.stats.glossaryTerms}** | **${total.withOutline}** | **${total.sources} (${total.checked})** |`,
  "",
  "¹ Concept outline with at least 2 key ideas and 1 misconception. ² Resolved OK in the last `npm run check:links` run.",
  `Generated by \`npm run report:coverage\` from content on ${new Date().toISOString().slice(0, 10)}.`,
].join("\n");

const lessonList = index.stages
  .map((s) => {
    const withLessons = s.conceptIds.filter((id) => index.concepts[id]!.lessonId);
    if (!withLessons.length) return `- **${s.shortTitle}:** no full lessons yet (outlines only).`;
    return `- **${s.shortTitle} (${withLessons.length}):** ${withLessons.map((id) => index.concepts[id]!.title).join(" · ")}`;
  })
  .join("\n");

function inject(file: string, block: string) {
  const path = resolve(root, file);
  if (!existsSync(path)) return;
  const text = readFileSync(path, "utf8");
  const start = "<!-- coverage:start -->";
  const end = "<!-- coverage:end -->";
  const i = text.indexOf(start);
  const j = text.indexOf(end);
  if (i < 0 || j < 0) {
    console.warn(`${file}: no coverage markers found; skipped`);
    return;
  }
  writeFileSync(path, `${text.slice(0, i + start.length)}\n${block}\n${text.slice(j)}`);
  console.log(`Updated ${file}`);
}

inject("CURRICULUM_AUDIT.md", table);
inject("ROADMAP.md", `${table}\n\n### Lessons available\n\n${lessonList}`);
console.log(table);
